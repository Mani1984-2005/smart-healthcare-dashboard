const BY_ID = new Map(MEDICINE_DATABASE.map((m) => [m.id, m]));

/** Flat list of { name, id, kind } for every generic + brand name, lower-cased. */
export const MEDICINE_NAME_INDEX = MEDICINE_DATABASE.flatMap((m) => [
  { name: m.genericName.toLowerCase(), id: m.id, kind: 'generic' },
  ...m.brandNames.map((b) => ({ name: b.toLowerCase(), id: m.id, kind: 'brand' })),
]);

export function getMedicineById(id) {
  return BY_ID.get(id) || null;
}

export function getInteraction(idA, idB) {
  const medA = BY_ID.get(idA);
  if (!medA) return null;
  const hit = medA.interactsWith.find((i) => i.id === idB);
  if (hit) return hit;
  const medB = BY_ID.get(idB);
  if (!medB) return null;
  return medB.interactsWith.find((i) => i.id === idA) || null;
}

export default MEDICINE_DATABASE;
